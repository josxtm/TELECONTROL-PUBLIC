#!/usr/bin/env python3
"""Inspect the actual preview package, permissions, resources and signing certificate."""
import argparse
import hashlib
from pathlib import Path
import re
import subprocess
import struct
import tempfile
import zipfile
from privacy_guard import check, APPROVED_UI_ASSETS, IP, KEY, PASSWORD, TOPOLOGY

OCR_SHA256 = {
    "assets/ocr/eng.traineddata": "7d4322bd2a7749724879683fc3912cb542f19906c83bcc1a52132556427170b2",
    "assets/ocr/spa.traineddata": "6f2e04d02774a18f01bed44b1111f2cd7f3ba7ac9dc4373cd3f898a40ea6b464",
}


# Exact native libraries included by pinned CameraX and OCR dependencies.
# Do not allow an arbitrary ELF merely because it is placed under lib/.
APPROVED_NATIVE_BASENAMES = frozenset({
    "libimage_processing_util_jni.so", "libsurface_util_jni.so",
    "libjpeg.so", "libleptonica.so", "libpngx.so", "libtesseract.so",
    # Added by pinned Compose graphics-path and DataStore dependencies.
    "libandroidx.graphics.path.so", "libdatastore_shared_counter.so",
})
EXPECTED_ELF_MACHINE = {
    "armeabi-v7a": 40, "arm64-v8a": 183, "x86": 3, "x86_64": 62,
}
MAX_NATIVE_BYTES = 32 * 1024 * 1024
# Kotlin standard library built-in descriptors bundled by pinned dependencies.
APPROVED_KOTLIN_BUILTINS = frozenset({
    "kotlin/annotation/annotation.kotlin_builtins",
    "kotlin/collections/collections.kotlin_builtins",
    "kotlin/coroutines/coroutines.kotlin_builtins",
    "kotlin/internal/internal.kotlin_builtins",
    "kotlin/kotlin.kotlin_builtins",
    "kotlin/ranges/ranges.kotlin_builtins",
    "kotlin/reflect/reflect.kotlin_builtins",
})


def inspect(apk, build_tools):
    apk = Path(apk)
    tools = Path(build_tools)
    def run(name, *args):
        return subprocess.check_output([str(tools / name), *map(str, args)], text=True)
    signature = run("apksigner", "verify", "--print-certs", apk)
    badging = run("aapt", "dump", "badging", apk)
    version = re.search(
        r"package: name='es\.josxtm\.telecontrol\.community' versionCode='([0-9]+)' versionName='v\.1\.0 public - comp\. ([0-9]+)'",
        badging
    )
    if not version or int(version.group(1)) != 10000 + int(version.group(2)):
        raise ValueError("Unexpected public application identity or compilation version")
    manifest = run("aapt", "dump", "xmltree", apk, "AndroidManifest.xml")
    permissions = re.findall(r"uses-permission: name='([^']+)'", badging)
    required_permissions = {"android.permission.RECORD_AUDIO", "android.permission.INTERNET", "android.permission.CAMERA"}
    permitted_permissions = required_permissions | {
        "android.permission.POST_NOTIFICATIONS", "android.permission.RECEIVE_BOOT_COMPLETED",
        "android.permission.SCHEDULE_EXACT_ALARM", "android.permission.WAKE_LOCK",
        "android.permission.ACCESS_NETWORK_STATE", "android.permission.FOREGROUND_SERVICE",
        "android.permission.FOREGROUND_SERVICE_DATA_SYNC", "android.permission.VIBRATE",
        "android.permission.ACCESS_WIFI_STATE",
        # Generated by AndroidX Core for same-package dynamically registered receivers.
        "es.josxtm.telecontrol.community.DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION"
    }
    actual_permissions = set(permissions)
    missing = sorted(required_permissions - actual_permissions)
    unexpected = sorted(actual_permissions - permitted_permissions)
    if missing or unexpected:
        # Permission *names* are not credentials or operational data. Log only
        # these names so CI diagnostics can be repaired without weakening gate.
        raise ValueError(
            "APK manifest permission mismatch; "
            + "missing required: " + ", ".join(missing or ["(none)"])
            + "; unexpected: " + ", ".join(unexpected or ["(none)"])
        )
    if "io.github.josxtm.mangossh.community.MainActivity" not in manifest or ":mangossh" not in manifest:
        raise ValueError("Isolated MangoSSH activity missing")
    if not re.search(r"allowBackup\([^\n]*=\(type 0x12\)0x0", manifest):
        raise ValueError("Automatic backup must be disabled")
    dex_strings = []
    xml_resources = []
    metadata = ""
    with zipfile.ZipFile(apk) as archive:
        # Report only JNI library basenames; never log file contents or private values.
        native_names = sorted({n.rsplit("/", 1)[-1] for n in archive.namelist()
            if n.startswith("lib/") and n.endswith(".so") and len(n) < 180})
        if native_names:
            print("Native library audit (names only): " + ", ".join(native_names), flush=True)
        if len(archive.namelist()) != len(set(archive.namelist())):
            raise ValueError("Duplicated APK archive path")
        for name in archive.namelist():
            if name.endswith("/"):
                continue
            if name in APPROVED_KOTLIN_BUILTINS:
                info = archive.getinfo(name)
                if info.file_size < 1 or info.file_size > 256 * 1024:
                    raise ValueError("Unexpected Kotlin builtin descriptor size")
                # The exact file name and bounded size are verified. These are
                # dependency metadata, not app content or stored CT records.
                continue
            if name == "META-INF/services/java.security.Provider":
                # Pinned Bouncy Castle registration; validate exact service classes.
                info = archive.getinfo(name)
                if info.file_size > 1024:
                    raise ValueError("Unexpected security provider descriptor size")
                entries = [line.strip() for line in archive.read(name).decode("utf-8").splitlines()
                           if line.strip() and not line.lstrip().startswith("#")]
                allowed = {"org.bouncycastle.jce.provider.BouncyCastleProvider",
                           "org.bouncycastle.jsse.provider.BouncyCastleJsseProvider",
                           "org.bouncycastle.pqc.jcajce.provider.BouncyCastlePQCProvider"}
                if not entries or len(entries) != len(set(entries)) or not set(entries).issubset(allowed):
                    # Class names alone (never credentials or document bodies) identify
                    # an unexpected dependency registration for a narrow future review.
                    unknown = sorted({entry for entry in entries if entry not in allowed
                                      and re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_.$]{0,180}", entry)})
                    raise ValueError("Unexpected security provider registration (classes only): "
                                     + ", ".join(unknown or ["invalid descriptor"]))
                continue
            if re.fullmatch(r"META-INF/services/kotlinx\.coroutines(?:\.[A-Za-z0-9_]+)+", name):
                # Kotlin coroutines ServiceLoader registrations are text metadata
                # from pinned runtime dependencies, never user- or CT-specific data.
                info = archive.getinfo(name)
                if info.file_size > 4096:
                    raise ValueError("Oversized coroutine service descriptor")
                services = archive.read(name).decode("utf-8").splitlines()
                services = [line.strip() for line in services if line.strip() and not line.lstrip().startswith("#")]
                if not services or any(not re.fullmatch(
                    r"kotlinx\.coroutines(?:\.[A-Za-z0-9_$]+)+", line) for line in services):
                    raise ValueError("Unexpected coroutine service registration")
                continue
            if re.fullmatch(
                r"org/bouncycastle/x509/CertPathReviewerMessages(?:_[a-z]{2})?\.properties", name
            ):
                # Public localization strings from the pinned Bouncy Castle jar.
                info = archive.getinfo(name)
                if info.file_size < 10 or info.file_size > 262144:
                    raise ValueError("Unexpected reviewed Bouncy Castle properties size")
                payload = archive.read(name)
                if b"\x00" in payload:
                    raise ValueError("Unexpected binary payload in Bouncy Castle properties")
                continue
            if name.startswith("lib/"):
                parts = name.split("/")
                if len(parts) != 3 or parts[1] not in EXPECTED_ELF_MACHINE or parts[2] not in APPROVED_NATIVE_BASENAMES:
                    raise ValueError("Unexpected native library path")
                entry = archive.getinfo(name)
                if entry.file_size < 64 or entry.file_size > MAX_NATIVE_BYTES:
                    raise ValueError("Unexpected native library size")
                native = archive.read(name)
                if (native[:4] != b"\x7fELF" or native[5] != 1
                        or int.from_bytes(native[18:20], "little") != EXPECTED_ELF_MACHINE[parts[1]]
                        or native[4] != (2 if parts[1] in {"arm64-v8a", "x86_64"} else 1)):
                    raise ValueError("Unexpected native ELF format or target")
                continue
            # Frontend files are audited by exact Git blob ID; OCR models are
            # public-licensed downloads with pinned SHA-256, never private CT data.
            if name.startswith("assets/"):
                ui_relative = "app/src/main/" + name
                content = archive.read(name)
                if ui_relative in APPROVED_UI_ASSETS:
                    header = b"blob " + str(len(content)).encode("ascii") + b"\x00"
                    git_sha = hashlib.sha1(header + content).hexdigest()
                    if git_sha != APPROVED_UI_ASSETS[ui_relative]:
                        raise ValueError("Unreviewed frontend content")
                elif name in OCR_SHA256:
                    if hashlib.sha256(content).hexdigest() != OCR_SHA256[name]:
                        raise ValueError("Unverified OCR language model")
                else:
                    raise ValueError("Unreviewed bundled asset")
                continue
            ui_image = bool(re.fullmatch(
                r"res/(?:drawable|mipmap)(?:-[A-Za-z0-9_-]+)?/[A-Za-z0-9_.-]+\.(?:png|webp|jpe?g)",
                name
            ))
            if ui_image:
                info = archive.getinfo(name)
                if info.file_size > 2 * 1024 * 1024 or info.file_size < 8:
                    raise ValueError("Unreviewed Android framework image size")
                image = archive.read(name)
                suffix = name.rsplit(".", 1)[-1].lower()
                valid = (
                    (suffix == "png" and image.startswith(bytes.fromhex("89504e470d0a1a0a")))
                    or (suffix == "webp" and image[:4] == b"RIFF" and image[8:12] == b"WEBP")
                    or (suffix in {"jpg", "jpeg"} and image.startswith(bytes.fromhex("ffd8")))
                )
                if not valid:
                    raise ValueError("Unreviewed Android framework image format")
            if not (re.fullmatch(r"classes\d*\.dex", name) or name in {"AndroidManifest.xml", "resources.arsc", "META-INF/com/android/build/gradle/app-metadata.properties"}
                    or re.fullmatch(r"res/[A-Za-z0-9_+/-]+\.xml", name)
                    or re.fullmatch(r"res/mipmap-(?:mdpi|hdpi|xhdpi|xxhdpi|xxxhdpi)(?:-v[0-9]+)?/ic_launcher\.png", name)
                    or ui_image
                    or re.fullmatch(r"META-INF/[A-Za-z0-9_.-]+", name)):
                safe_name = re.sub(r"[^A-Za-z0-9_./+-]", "?", name)[:160]
                raise ValueError("Unreviewed packaged resource path: " + safe_name)
            if name.startswith("res/raw") or name.startswith("assets/"):
                raise ValueError("Bundled data is forbidden")
            if name.startswith("res/mipmap-") and name.endswith("/ic_launcher.png"):
                artwork = archive.read(name)
                if not artwork.startswith(bytes.fromhex("89504e470d0a1a0a")) or len(artwork) > 100000:
                    raise ValueError("Unreviewed launcher image payload")
            if name.startswith("res/") and name.endswith(".xml"):
                xml_resources.append(run("aapt", "dump", "xmltree", apk, name))
            if name.endswith("app-metadata.properties"):
                metadata = archive.read(name).decode("utf-8")
            if re.fullmatch(r"classes\d*\.dex", name):
                data = archive.read(name)
                if not data.startswith(b"dex\n"):
                    raise ValueError("Invalid bytecode container")
                count, table = struct.unpack_from("<II", data, 56)
                for index in range(count):
                    offset, = struct.unpack_from("<I", data, table + 4 * index)
                    for _ in range(5):
                        byte = data[offset]
                        offset += 1
                        if byte < 128:
                            break
                    end = data.index(b"\0", offset)
                    dex_strings.append(data[offset:end].decode("utf-8", errors="replace"))
    resources = run("aapt", "dump", "resources", apk)
    # Corporate branding and field captions may legitimately exist in public
    # GUI bytecode. Reject credentials, literal operational IPs and topology,
    # rather than treating every public brand name as confidential.
    compiled = resources + "\n" + "\n".join(xml_resources) + "\n" + metadata + "\n" + "\n".join(dex_strings)
    # GL.iNet Mango (GL-MT300N-V2) publicly documented factory gateway.
    # This exception is exact; all other non-system IPv4 literals remain blocked.
    whitelist_ip = {
        ".".join(parts) for parts in (
            ("0", "0", "0", "0"), ("127", "0", "0", "1"),
            ("255", "255", "255", "255"), ("192", "168", "8", "1"),
        )
    }
    # Report pattern categories only: never print potential credentials, IPs or
    # operational strings from DEX and resources into a public CI log.
    flagged = []
    # Diagnose the origin without ever exposing the matched address in public logs.
    ip_sources = {
        "compiled resources": resources,
        "compiled XML": "\n".join(xml_resources),
        "APK metadata": metadata,
        "DEX constants": "\n".join(dex_strings),
    }
    ip_categories = [label for label, payload in ip_sources.items()
                     if any(value not in whitelist_ip for value in IP.findall(payload))]
    if ip_categories:
        flagged.append("IPv4 literal (sources: " + ", ".join(ip_categories) + ")")
    # JSch's public SSH key *parser* embeds a PEM header marker as a
    # constant. A header alone is not a credential. Reject actual PEM key
    # material (header, substantial base64 body and matching footer) and tokens.
    embedded_token = re.search(r"(?:github_pat_|gh[pousr]_)[A-Za-z0-9_]{16,}", compiled)
    embedded_pem = re.search(
        r"-{5}BEGIN ([A-Z ]*PRIVATE KEY)-{5}\s*[A-Za-z0-9+/=\s]{96,}-"
        r"{5}END \1-{5}", compiled
    )
    if embedded_token or embedded_pem:
        flagged.append("embedded credential material")
    if PASSWORD.search(compiled):
        flagged.append("password assignment")
    if TOPOLOGY.search(compiled):
        flagged.append("network topology expression")
    if flagged:
        raise ValueError("Compiled output contains potentially private operational content: " + ", ".join(flagged))
    certs = "\n".join(line for line in signature.splitlines() if "certificate SHA-256 digest:" in line)
    if not certs:
        raise ValueError("No verified certificate fingerprint")
    return ("PASS APK identity, version, signature, permission allowlist and resource inspection\n"
            + certs + "\nAPK SHA-256: " + hashlib.sha256(apk.read_bytes()).hexdigest()
            + "\nPreview only: independent public application; ephemeral debug signing.\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("apk")
    parser.add_argument("build_tools")
    args = parser.parse_args()
    print(inspect(args.apk, args.build_tools), end="")
